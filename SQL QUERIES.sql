-- 8. Find the average customer rating per vehicle type:
CREATE VIEW CUSTOMER_RATING_PER_VEHICLE_TYPE AS
SELECT VEHICLE_TYPE,ROUND(AVG(CUSTOMER_RATING),2) AS AVG_CUSOMER_RATINGS
FROM BOOKINGS
GROUP BY VEHICLE_TYPE;
-- 
SELECT * FROM CUSTOMER_RATING_PER_VEHICLE_TYPE;
-- PRIME PLUS HAS THE HIGHEST AVERAGE CUSTOMER RATING OF 4.01 AMONG ALL VEHICLE TYPES.   
-- BIKE AND EBIKE HAVE THE LOWEST AVERAGE CUSTOMER RATINGS OF 3.99.   
-- PRIME SEDAN, PRIME SUV, MINI, AND AUTO ALL HAVE AN AVERAGE CUSTOMER RATING OF 4. 
--
-- 9. Calculate the total booking value of rides completed successfully:
CREATE VIEW TOTAL_BOOKING_VALUE_FOR_SUCCESSFUL_RIDES AS 
SELECT SUM(BOOKING_VALUE) AS TOTAL_BOOKING_VALUE
FROM BOOKINGS
WHERE BOOKING_STATUS = 'SUCCESS';
--
SELECT * FROM TOTAL_BOOKING_VALUE_FOR_SUCCESSFUL_RIDES;
-- TOTAL BOOKING VALUE FOR THE SUCCESSFUL RIDES ARE 35080467.
--
-- 10. List all incomplete rides along with the reason:
CREATE VIEW INCOMPLETE_BOOKINGS AS 
SELECT BOOKING_ID,INCOMPLETE_RIDES_REASON
FROM BOOKINGS
WHERE INCOMPLETE_RIDES = 'YES';
-- 
SELECT INCOMPLETE_RIDES_REASON,COUNT(BOOKING_ID) AS CANCELLATION_COUNT
FROM INCOMPLETE_BOOKINGS 
